  static UserModel findPatientByAarogyasriId(String query) {
    final clean = query.trim();
    if (clean.isEmpty) return defaultUser;

    // 1. If payload contains full QR encoded format or JSON, decode real data
    if (clean.startsWith('HEALTHEXPRESS:AAROGYASRI:') ||
        clean.startsWith('AAROGYASRI:') ||
        clean.contains('|') ||
        (clean.startsWith('{') && clean.endsWith('}'))) {
      final parsed = UserModel.fromAarogyasriQrPayload(clean);
      if (parsed.name.isNotEmpty && parsed.name != 'Verified Citizen') {
        if (!registeredPatients.any((p) => p.aarogyasriId.toLowerCase() == parsed.aarogyasriId.toLowerCase() && p.aarogyasriId.isNotEmpty)) {
          registeredPatients.insert(0, parsed);
        }
        return parsed;
      }
    }

    final upper = clean.toUpperCase();

    // 2. Exact or fuzzy match in registered patients
    for (final p in registeredPatients) {
      if (p.aarogyasriId.toUpperCase() == upper ||
          p.id.toUpperCase() == upper ||
          p.phone == clean ||
          p.name.toUpperCase().contains(upper) ||
          upper.contains(p.aarogyasriId.toUpperCase())) {
        return p;
      }
    }

