  static Future<void> syncWithLiveBackend() async {
    try {
      debugPrint('🔄 Synchronizing ProductionDatabase with Live Hostinger MySQL backend...');

      // 1. Sync Live Hospitals
      final liveHospitals = await ApiService.fetchHospitals();
      if (liveHospitals.isNotEmpty) {
        hospitals = liveHospitals;
        debugPrint('✅ Loaded ${liveHospitals.length} Real Hospitals from Hostinger MySQL');
      }

      // 2. Sync Live Doctors
      final liveDoctors = await ApiService.fetchDoctors();
      if (liveDoctors.isNotEmpty) {
        doctors = liveDoctors;
        debugPrint('✅ Loaded ${liveDoctors.length} Real Doctors from Hostinger MySQL');
      }

      // 3. Sync Live Medicines
      final liveMedicines = await ApiService.fetchMedicines();
      if (liveMedicines.isNotEmpty) {
        medicines = liveMedicines;
        debugPrint('✅ Loaded ${liveMedicines.length} Real Medicines from Hostinger MySQL');
      }

      isLiveSynced = true;
      debugPrint('🎉 ProductionDatabase Live Backend Sync Complete!');
    } catch (e) {
      debugPrint('Live backend sync notice: $e');
    }
  }
